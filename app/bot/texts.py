"""Тексты, которые видит пользователь.

Собраны в одном месте по двум причинам: их правят чаще всего, и их формулировки —
это обещания, которые бот даёт человеку насчёт его учётных данных. Такие вещи
должны быть на виду, а не разбросаны по обработчикам.

Разметка — HTML (`parse_mode="HTML"`): в отличие от MarkdownV2, он не требует
экранировать точки, дефисы и скобки, которых в русском тексте полно.
"""

from __future__ import annotations

from app.bot.commands import COMMANDS

TELEGRAM_MESSAGE_LIMIT = 4096

GREETING = "Привет! Я показываю ваше расписание из личного кабинета РАНХиГС и умею класть его в календарь телефона."

HOW_IT_WORKS = """<b>Как это работает</b>

1. Вы один раз подключаете личный кабинет командой /login.
2. Каждую ночь я захожу в кабинет от вашего имени и забираю расписание.
3. Пары можно смотреть прямо здесь или подписать на них календарь — тогда они появятся в приложении телефона и будут обновляться сами.

Если пару перенесут или отменят, я пришлю сообщение и поправлю событие в календаре."""

HONEST_PART = """<b>Что нужно знать</b>

• Бот неофициальный и с академией никак не связан.
• <b>Пароль я не храню.</b> Он нужен один раз, при подключении: кабинет выдаёт в ответ ключ доступа, и дальше я работаю только с ним. Сообщение с паролем удаляется из чата сразу.
• Ключ доступа хранится в зашифрованном виде. Он открывает только ваш личный кабинет и перестаёт работать после /logout.
• Ссылка на календарь содержит секретный ключ — у любого, кто её получит, будет ваше расписание. Ссылку можно перевыпустить в /settings.
• Команда /logout удаляет всё, что я о вас храню, без остатка.
• Исходный код открыт, его можно прочитать и развернуть свою копию: https://github.com/Ekanam-Friends/Ikanam-schedule"""

NOT_CONNECTED_HINT = "Пока личный кабинет не подключён — начните с /login."


def build_commands_block() -> str:
    """Список команд с объяснениями — ровно тот, что зарегистрирован в Telegram."""
    lines = [f"/{command.name} — {command.explanation}" for command in COMMANDS]
    return "<b>Команды</b>\n\n" + "\n".join(lines)


def build_start_message(*, is_connected: bool = False) -> str:
    """Текст `/start`.

    Человеку, который ещё не подключил кабинет, в конце добавляется подсказка,
    с чего начать: список из девяти команд сам по себе не отвечает на вопрос
    «а что нажать сейчас».
    """
    blocks = [GREETING, HOW_IT_WORKS, build_commands_block(), HONEST_PART]
    if not is_connected:
        blocks.append(NOT_CONNECTED_HINT)
    return "\n\n".join(blocks)
